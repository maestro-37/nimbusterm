def escape(value: str) -> str:
    return value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def write_lproj(code: str, mapping: dict[str, str]) -> None:
    path = RES / f"{code}.lproj"
    path.mkdir(parents=True, exist_ok=True)
    lines = ["/* NimbusTerm localization */", ""]
    for key in sorted(mapping):
        lines.append(f'"{escape(key)}" = "{escape(mapping[key])}";')
    (path / "Localizable.strings").write_text("\n".join(lines) + "\n", encoding="utf-8")


